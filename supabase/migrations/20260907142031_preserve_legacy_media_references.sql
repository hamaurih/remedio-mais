create table if not exists public.legacy_media_refs (
  id bigint generated by default as identity primary key,
  entity_type text not null check (entity_type in ('product','banner')),
  entity_id uuid not null,
  field_name text not null,
  source_url text not null,
  captured_at timestamptz not null default now(),
  unique(entity_type, entity_id, field_name, source_url)
);
alter table public.legacy_media_refs enable row level security;
revoke all on table public.legacy_media_refs from anon, authenticated;
comment on table public.legacy_media_refs is 'Preserva URLs de mídia do storage legado para eventual recuperação futura; acesso apenas administrativo/server-side.';
